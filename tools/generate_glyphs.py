#!/usr/bin/env python3
"""Generate the UTF-8 string corpus used to build the raylib glyph atlas."""
from __future__ import annotations
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "ui" / "GeneratedGlyphs.h"
STRING_RE = re.compile(r'(?<![A-Za-z0-9_])"((?:\\.|[^"\\])*)"')


def decode_cpp(text: str) -> str:
    out: list[str] = []
    i = 0
    escapes = {"n": "\n", "r": "\r", "t": "\t", "b": "\b", "f": "\f", "v": "\v", "a": "\a", "\\": "\\", '"': '"', "?": "?"}
    while i < len(text):
        if text[i] != "\\" or i + 1 >= len(text):
            out.append(text[i]); i += 1; continue
        c = text[i + 1]
        if c in escapes:
            out.append(escapes[c]); i += 2; continue
        if c == "x" and i + 3 < len(text):
            m = re.match(r"[0-9A-Fa-f]{2}", text[i + 2:i + 4])
            if m:
                out.append(chr(int(m.group(), 16))); i += 4; continue
        # Preserve unknown escapes as the escaped character; this is enough for glyph coverage.
        out.append(c); i += 2
    return "".join(out)


def main() -> None:
    corpus: set[str] = set()
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix not in {".cpp", ".h"} or path.name == OUT.name:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for match in STRING_RE.finditer(text):
            value = decode_cpp(match.group(1))
            if value:
                corpus.add(value)
    values = sorted(corpus)
    lines = [
        "#pragma once",
        "// Generated by tools/generate_glyphs.py; do not edit by hand.",
        "#include <cstddef>",
        "namespace piano::ui_generated {",
        "inline constexpr const char* kSourceStrings[] = {",
    ]
    lines.extend(f"    {json.dumps(value, ensure_ascii=False)}," for value in values)
    lines += ["};", "inline constexpr std::size_t kSourceStringCount = sizeof(kSourceStrings) / sizeof(kSourceStrings[0]);", "}", ""]
    content = "\n".join(lines)
    if OUT.exists() and OUT.read_text(encoding="utf-8") == content:
        return
    if "--check" in sys.argv:
        print(f"stale generated glyph file: {OUT.relative_to(ROOT)}")
        raise SystemExit(1)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"generated {OUT.relative_to(ROOT)} ({len(values)} strings)")


if __name__ == "__main__":
    main()
